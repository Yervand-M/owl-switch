import AppKit

/// One remembered copy: the clipboard data plus what to show for it in the menu.
struct Clip: Identifiable {
    enum Kind { case text, image, files }

    let id = UUID()
    let kind: Kind
    let title: String          // one line for the menu
    let tooltip: String?
    let icon: NSImage?
    let signature: Data        // identical copies share a signature, so they aren't listed twice
    let items: [[NSPasteboard.PasteboardType: Data]]
}

/// Windows-style clipboard history: remembers the last 25 copies, in memory only (never written to disk).
/// Copies that password managers mark as private are skipped.
final class ClipboardHistory {
    static let limit = 25
    private static let maxBytes = 30_000_000

    // Formats worth keeping; app-private formats are dropped. PNG comes before TIFF so images keep only one.
    private static let keptTypes: [NSPasteboard.PasteboardType] = [.fileURL, .URL, .string, .rtf, .rtfd, .html, .png, .tiff]
    // "Don't record this" markers used by password managers and similar apps (nspasteboard.org).
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    private(set) var items: [Clip] = []
    var isEnabled = true { didSet { if !isEnabled { items.removeAll() } } }
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    func clear() { items.removeAll() }

    func remove(_ clip: Clip) { items.removeAll { $0.id == clip.id } }

    /// Puts a remembered copy back on the clipboard; it then moves to the top of the list.
    func restore(_ clip: Clip) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.writeObjects(clip.items.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        })
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        guard isEnabled, let clip = Self.capture(pb) else { return }
        items.removeAll { $0.signature == clip.signature }
        items.insert(clip, at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    private static func capture(_ pb: NSPasteboard) -> Clip? {
        if (pb.types ?? []).contains(where: { privateTypes.contains($0.rawValue) }) { return nil }

        var snapshot: [[NSPasteboard.PasteboardType: Data]] = []
        var bytes = 0
        for item in pb.pasteboardItems ?? [] {
            var kept: [NSPasteboard.PasteboardType: Data] = [:]
            for type in keptTypes where item.types.contains(type) {
                if type == .tiff, kept[.png] != nil { continue }
                guard let data = item.data(forType: type) else { continue }
                kept[type] = data
                bytes += data.count
            }
            if !kept.isEmpty { snapshot.append(kept) }
        }
        guard !snapshot.isEmpty, bytes <= maxBytes else { return nil }

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           let first = urls.first {
            let names = urls.map(\.lastPathComponent)
            let icon = NSWorkspace.shared.icon(forFile: first.path)
            icon.size = NSSize(width: 16, height: 16)
            return Clip(kind: .files,
                        title: names.count == 1 ? names[0] : "\(names[0]) + \(names.count - 1) more",
                        tooltip: names.joined(separator: "\n"), icon: icon,
                        signature: Data(urls.map(\.path).joined(separator: "\n").utf8), items: snapshot)
        }
        if let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return Clip(kind: .text, title: oneLine(text), tooltip: String(text.prefix(600)), icon: nil,
                        signature: Data(text.utf8), items: snapshot)
        }
        if let data = snapshot[0][.png] ?? snapshot[0][.tiff], let image = NSImage(data: data) {
            let px = image.representations.first.map { "\($0.pixelsWide) × \($0.pixelsHigh)" } ?? ""
            return Clip(kind: .image, title: "Image \(px)", tooltip: nil, icon: thumbnail(image),
                        signature: data, items: snapshot)
        }
        return nil
    }

    private static func oneLine(_ text: String) -> String {
        let flat = text.split(whereSeparator: \.isWhitespace).joined(separator: " ")
        return flat.count > 60 ? String(flat.prefix(60)) + "…" : flat
    }

    private static func thumbnail(_ image: NSImage) -> NSImage {
        let box = NSSize(width: 40, height: 28)
        return NSImage(size: box, flipped: false) { rect in
            let scale = min(rect.width / max(image.size.width, 1), rect.height / max(image.size.height, 1))
            let size = NSSize(width: image.size.width * scale, height: image.size.height * scale)
            image.draw(in: NSRect(x: (rect.width - size.width) / 2, y: (rect.height - size.height) / 2,
                                  width: size.width, height: size.height))
            return true
        }
    }
}

/// The Option+V menu: opens at the mouse pointer, keys 1–9 pick an item, Return pastes the highlighted one.
final class HistoryMenu: NSObject {
    private let history: ClipboardHistory
    private let toast: Toast

    init(history: ClipboardHistory, toast: Toast) {
        self.history = history
        self.toast = toast
    }

    func show() {
        let menu = NSMenu()
        menu.autoenablesItems = false
        let header = NSMenuItem(title: history.items.isEmpty ? "Clipboard history is empty — copy something first"
                                                             : "Clipboard History", action: nil, keyEquivalent: "")
        header.isEnabled = false
        menu.addItem(header)

        for (index, clip) in history.items.enumerated() {
            let item = NSMenuItem(title: clip.title, action: #selector(pick(_:)),
                                  keyEquivalent: index < 9 ? "\(index + 1)" : "")
            item.keyEquivalentModifierMask = []
            item.target = self
            item.representedObject = clip.id
            item.image = clip.icon
            item.toolTip = clip.tooltip
            menu.addItem(item)
        }
        if !history.items.isEmpty {
            menu.addItem(.separator())
            let clear = NSMenuItem(title: "Clear History", action: #selector(clear), keyEquivalent: "")
            clear.target = self
            menu.addItem(clear)
        }
        menu.popUp(positioning: nil, at: NSEvent.mouseLocation, in: nil)
    }

    @objc private func pick(_ sender: NSMenuItem) {
        guard let id = sender.representedObject as? UUID,
              let clip = history.items.first(where: { $0.id == id }) else { return }
        history.restore(clip)
        if Accessibility.isTrusted {
            // Give the menu a moment to close so the paste lands in the app underneath.
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) { KeyboardTap.post(Key.v, flags: .maskCommand) }
        } else {
            toast.show("Copied — press ⌘V to paste")
        }
    }

    @objc private func clear() { history.clear() }
}
